-- 008_admin_salary.sql  (Bagian 5 — gaji Admin bulanan, mengikuti menu "Admin & Designer" Sablon)
--
-- Isi:
--   1. salary_fixed        — gaji tetap per bulan per orang. HANYA DITAMBAH (riwayat per tanggal
--                            berlaku, id terbesar menang di tanggal yang sama), tidak bisa diubah/dihapus
--                            dari aplikasi — sama seperti pricing_configs.
--   2. salary_bonus_manual — bonus tambahan yang diisi manual per bulan (boleh dihapus bila salah ketik).
--   3. salary_closings     — pesanan yang dipilih sebagai closing seorang admin pada suatu bulan
--                            (satu pesanan hanya boleh jadi closing satu orang).
--
-- Pembayaran TIDAK butuh tabel baru: tetap salary_payments kategori 'admin' lewat
-- mark_salary_paid / unmark_salary_paid dari migration 007.
--
-- Prasyarat: 001–007 sudah dijalankan. Aman dijalankan ulang (idempotent).
-- Dijalankan di SQL Editor sebagai postgres (pemilik tabel).

begin;

-- ─── 1. Gaji tetap ───────────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.salary_fixed (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references monitoring_konveksi.users(id) on delete cascade,
  amount         numeric(14, 0) not null check (amount >= 0),
  effective_date date not null,
  created_by     uuid default auth.uid() references monitoring_konveksi.users(id) on delete set null,
  created_at     timestamptz not null default timezone('utc', now())
);
create index if not exists salary_fixed_user_idx
  on monitoring_konveksi.salary_fixed (user_id, effective_date desc, id desc);

-- ─── 2. Bonus tambahan manual ────────────────────────────────────────────────
create table if not exists monitoring_konveksi.salary_bonus_manual (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null references monitoring_konveksi.users(id) on delete cascade,
  period_month  smallint not null check (period_month between 1 and 12),
  period_year   smallint not null check (period_year between 2020 and 2100),
  label         text not null check (char_length(btrim(label)) between 1 and 200),
  amount        numeric(14, 0) not null check (amount > 0),
  created_by    uuid default auth.uid() references monitoring_konveksi.users(id) on delete set null,
  created_at    timestamptz not null default timezone('utc', now())
);
create index if not exists salary_bonus_manual_period_idx
  on monitoring_konveksi.salary_bonus_manual (period_year, period_month);

-- ─── 3. Closing admin ────────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.salary_closings (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null references monitoring_konveksi.users(id) on delete cascade,
  order_id      uuid not null references monitoring_konveksi.orders(id) on delete cascade,
  period_month  smallint not null check (period_month between 1 and 12),
  period_year   smallint not null check (period_year between 2020 and 2100),
  created_by    uuid default auth.uid() references monitoring_konveksi.users(id) on delete set null,
  created_at    timestamptz not null default timezone('utc', now()),
  unique (order_id)
);
create index if not exists salary_closings_period_idx
  on monitoring_konveksi.salary_closings (period_year, period_month);

-- ─── 4. Akses & RLS ──────────────────────────────────────────────────────────
-- lihat = Gaji & Upah → Lihat; tambah/hapus = Gaji & Upah → Edit. salary_fixed tidak punya
-- update/delete sama sekali (riwayat gaji tetap tidak boleh diubah).
grant select, insert, update, delete
  on monitoring_konveksi.salary_fixed,
     monitoring_konveksi.salary_bonus_manual,
     monitoring_konveksi.salary_closings
  to service_role;

revoke update, delete on monitoring_konveksi.salary_fixed         from authenticated;
revoke update         on monitoring_konveksi.salary_bonus_manual  from authenticated;
revoke update         on monitoring_konveksi.salary_closings      from authenticated;
grant select, insert         on monitoring_konveksi.salary_fixed         to authenticated;
grant select, insert, delete on monitoring_konveksi.salary_bonus_manual  to authenticated;
grant select, insert, delete on monitoring_konveksi.salary_closings      to authenticated;

alter table monitoring_konveksi.salary_fixed        enable row level security;
alter table monitoring_konveksi.salary_bonus_manual enable row level security;
alter table monitoring_konveksi.salary_closings     enable row level security;

drop policy if exists "Gaji tetap: baca" on monitoring_konveksi.salary_fixed;
create policy "Gaji tetap: baca" on monitoring_konveksi.salary_fixed
  for select to authenticated using (monitoring_konveksi.has_perm('salary', 'view'));
drop policy if exists "Gaji tetap: tambah" on monitoring_konveksi.salary_fixed;
create policy "Gaji tetap: tambah" on monitoring_konveksi.salary_fixed
  for insert to authenticated
  with check (monitoring_konveksi.has_perm('salary', 'edit') and created_by = auth.uid());

drop policy if exists "Bonus manual: baca" on monitoring_konveksi.salary_bonus_manual;
create policy "Bonus manual: baca" on monitoring_konveksi.salary_bonus_manual
  for select to authenticated using (monitoring_konveksi.has_perm('salary', 'view'));
drop policy if exists "Bonus manual: tambah" on monitoring_konveksi.salary_bonus_manual;
create policy "Bonus manual: tambah" on monitoring_konveksi.salary_bonus_manual
  for insert to authenticated
  with check (monitoring_konveksi.has_perm('salary', 'edit') and created_by = auth.uid());
drop policy if exists "Bonus manual: hapus" on monitoring_konveksi.salary_bonus_manual;
create policy "Bonus manual: hapus" on monitoring_konveksi.salary_bonus_manual
  for delete to authenticated using (monitoring_konveksi.has_perm('salary', 'edit'));

drop policy if exists "Closing: baca" on monitoring_konveksi.salary_closings;
create policy "Closing: baca" on monitoring_konveksi.salary_closings
  for select to authenticated using (monitoring_konveksi.has_perm('salary', 'view'));
drop policy if exists "Closing: tambah" on monitoring_konveksi.salary_closings;
create policy "Closing: tambah" on monitoring_konveksi.salary_closings
  for insert to authenticated
  with check (monitoring_konveksi.has_perm('salary', 'edit') and created_by = auth.uid());
drop policy if exists "Closing: hapus" on monitoring_konveksi.salary_closings;
create policy "Closing: hapus" on monitoring_konveksi.salary_closings
  for delete to authenticated using (monitoring_konveksi.has_perm('salary', 'edit'));

commit;

-- Minta PostgREST (API Supabase) memuat ulang daftar tabel baru.
notify pgrst, 'reload schema';
