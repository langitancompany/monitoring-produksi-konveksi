-- 009_finance_foundation.sql  (Bagian 6, LANGKAH 6.1 — fondasi Keuangan)
--
-- Isi (hanya fondasi; tagihan/pembayaran/pengeluaran menyusul di langkah 6.2–6.8):
--   1. finance_settings    — pengaturan keuangan (kunci → nilai jsonb)
--   2. finance_accounts    — akun kas / bank / e-wallet
--   3. finance_categories  — kategori pengeluaran (dipakai langkah 6.5 & posting gaji 6.8)
--   4. finance_audit_log   — jejak audit, APPEND-ONLY (trigger menolak ubah/hapus/truncate)
--   5. fin_audit()         — satu-satunya jalan menulis log audit dari fungsi keuangan lain
--
-- Prinsip (mengikuti Keuangan v2 Sablon): SEMUA operasi uang lewat API server (service role).
-- Browser tidak diberi akses langsung ke tabel keuangan sama sekali — tanpa grant dan tanpa policy.
--
-- ⚠ Data awal di bawah (akun, kategori, pengaturan) adalah ASUMSI BAWAAN — definisi asli seed
--   Sablon belum tersedia (PRD §13.3). Sesuaikan lewat SQL Editor sebelum dipakai sungguhan.
--
-- Prasyarat: 001–008 sudah dijalankan. Aman dijalankan ulang (idempotent).
-- Dijalankan di SQL Editor sebagai postgres (pemilik tabel).

begin;

-- ─── 1. Pengaturan ───────────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.finance_settings (
  key         text primary key check (key ~ '^[a-z0-9_]{2,60}$'),
  value       jsonb not null,
  updated_at  timestamptz not null default timezone('utc', now()),
  updated_by  uuid references monitoring_konveksi.users(id) on delete set null
);

-- ─── 2. Akun kas / bank ──────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.finance_accounts (
  id          uuid primary key default gen_random_uuid(),
  code        text not null unique check (code ~ '^[A-Z0-9_]{2,20}$'),
  name        text not null check (char_length(btrim(name)) between 1 and 80),
  type        text not null check (type in ('cash', 'bank', 'ewallet')),
  is_active   boolean not null default true,
  sort_order  integer not null default 100,
  created_at  timestamptz not null default timezone('utc', now())
);

-- ─── 3. Kategori ─────────────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.finance_categories (
  id          uuid primary key default gen_random_uuid(),
  code        text not null unique check (code ~ '^[A-Z0-9_]{2,20}$'),
  name        text not null check (char_length(btrim(name)) between 1 and 80),
  kind        text not null default 'expense' check (kind in ('expense', 'income')),
  is_active   boolean not null default true,
  sort_order  integer not null default 100,
  created_at  timestamptz not null default timezone('utc', now())
);

-- ─── 4. Log audit (append-only) ──────────────────────────────────────────────
-- actor_id / entity_id / order_id sengaja TANPA foreign key: jejak audit harus tetap ada walau
-- user dihapus atau order dibersihkan.
create table if not exists monitoring_konveksi.finance_audit_log (
  id          bigint generated by default as identity primary key,
  at          timestamptz not null default timezone('utc', now()),
  actor_id    uuid,
  actor_name  text,
  action      text not null check (char_length(btrim(action)) between 1 and 60),
  entity      text not null check (char_length(btrim(entity)) between 1 and 40),
  entity_id   uuid,
  order_id    uuid,
  before      jsonb,
  after       jsonb,
  reason      text
);
create index if not exists finance_audit_log_at_idx     on monitoring_konveksi.finance_audit_log (at desc);
create index if not exists finance_audit_log_entity_idx on monitoring_konveksi.finance_audit_log (entity, entity_id);
create index if not exists finance_audit_log_order_idx  on monitoring_konveksi.finance_audit_log (order_id) where order_id is not null;

create or replace function monitoring_konveksi.fin_audit_immutable()
returns trigger language plpgsql set search_path = monitoring_konveksi, public as $$
begin
  raise exception 'FIN: Log audit tidak boleh diubah atau dihapus';
end $$;

drop trigger if exists finance_audit_log_no_change on monitoring_konveksi.finance_audit_log;
create trigger finance_audit_log_no_change
  before update or delete on monitoring_konveksi.finance_audit_log
  for each row execute function monitoring_konveksi.fin_audit_immutable();

drop trigger if exists finance_audit_log_no_truncate on monitoring_konveksi.finance_audit_log;
create trigger finance_audit_log_no_truncate
  before truncate on monitoring_konveksi.finance_audit_log
  for each statement execute function monitoring_konveksi.fin_audit_immutable();

-- ─── 5. fin_audit() ──────────────────────────────────────────────────────────
-- Dipanggil oleh fungsi keuangan lain (langkah 6.2+) di dalam transaksi yang sama dengan
-- perubahan uangnya, jadi tidak ada perubahan tanpa jejak.
create or replace function monitoring_konveksi.fin_audit(
  p_actor uuid, p_actor_name text,
  p_action text, p_entity text, p_entity_id uuid, p_order uuid,
  p_before jsonb, p_after jsonb, p_reason text
) returns void
language sql security definer set search_path = monitoring_konveksi, public as $$
  insert into monitoring_konveksi.finance_audit_log
    (actor_id, actor_name, action, entity, entity_id, order_id, before, after, reason)
  values
    (p_actor, left(p_actor_name, 120), p_action, p_entity, p_entity_id, p_order, p_before, p_after,
     nullif(left(btrim(coalesce(p_reason, '')), 500), ''));
$$;

revoke all on function monitoring_konveksi.fin_audit(uuid, text, text, text, uuid, uuid, jsonb, jsonb, text)
  from public, anon, authenticated;
grant execute on function monitoring_konveksi.fin_audit(uuid, text, text, text, uuid, uuid, jsonb, jsonb, text)
  to service_role;

-- ─── 6. Akses: hanya server (service_role) ───────────────────────────────────
alter table monitoring_konveksi.finance_settings   enable row level security;
alter table monitoring_konveksi.finance_accounts   enable row level security;
alter table monitoring_konveksi.finance_categories enable row level security;
alter table monitoring_konveksi.finance_audit_log  enable row level security;

revoke all on monitoring_konveksi.finance_settings,
              monitoring_konveksi.finance_accounts,
              monitoring_konveksi.finance_categories,
              monitoring_konveksi.finance_audit_log
  from public, anon, authenticated;

grant select, insert, update, delete
  on monitoring_konveksi.finance_settings,
     monitoring_konveksi.finance_accounts,
     monitoring_konveksi.finance_categories
  to service_role;
-- Log audit: server hanya boleh MENAMBAH dan MEMBACA (trigger di atas menolak ubah/hapus juga).
grant select, insert on monitoring_konveksi.finance_audit_log to service_role;
grant usage on all sequences in schema monitoring_konveksi to service_role;

