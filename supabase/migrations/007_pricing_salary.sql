-- pricing_configs: lihat = Config Harga (lihat/edit) atau Gaji (lihat, perlu rate untuk menghitung);
-- tambah = Config Harga → Edit. Tidak ada policy update/delete (riwayat tidak boleh diubah).
drop policy if exists "Harga: baca" on monitoring_konveksi.pricing_configs;
create policy "Harga: baca" on monitoring_konveksi.pricing_configs
  for select to authenticated
  using (   monitoring_konveksi.has_perm('config_harga', 'view')
         or monitoring_konveksi.has_perm('config_harga', 'edit')
         or monitoring_konveksi.has_perm('salary', 'view'));

drop policy if exists "Harga: tambah" on monitoring_konveksi.pricing_configs;
create policy "Harga: tambah" on monitoring_konveksi.pricing_configs
  for insert to authenticated
  with check (monitoring_konveksi.has_perm('config_harga', 'edit')
              and created_by = auth.uid());

drop policy if exists "Gaji: baca pembayaran" on monitoring_konveksi.salary_payments;
create policy "Gaji: baca pembayaran" on monitoring_konveksi.salary_payments
  for select to authenticated using (monitoring_konveksi.has_perm('salary', 'view'));

drop policy if exists "Gaji: baca jejak" on monitoring_konveksi.salary_audit_log;
create policy "Gaji: baca jejak" on monitoring_konveksi.salary_audit_log
  for select to authenticated using (monitoring_konveksi.has_perm('salary', 'view'));

-- ─── 8. Nilai awal parameter aturan ──────────────────────────────────────────
-- Berlaku sejak 2000-01-01 supaya semua pesanan lama ikut memakainya. Nilai bonus admin = nilai
-- Sablon, 70% PJ = sistem lama Sablon (PRD §17) — ASUMSI: ubah di menu Config Harga bila berbeda.
-- Rate per jenis produksi TIDAK diisi di sini (belum ada angkanya) → diisi pemilik di Config Harga.
insert into monitoring_konveksi.pricing_configs
  (category, key_name, display_name, unit, value_amount, effective_date)
select v.category, v.key_name, v.display_name, v.unit, v.value_amount, v.effective_date
  from (values
    ('PARAMETER', 'pj_share_percent',       'Bagian PJ dari gaji produksi',      'persen', 70,    date '2000-01-01'),
    ('PARAMETER', 'bonus_admin_closing',    'Bonus admin per closing',           'Rp',     10000, date '2000-01-01'),
    ('PARAMETER', 'batas_pcs_bonus_admin',  'Batas pcs bonus admin',             'pcs',    50,    date '2000-01-01'),
    ('PARAMETER', 'bonus_admin_per_pcs',    'Bonus admin per pcs di atas batas', 'Rp',     500,   date '2000-01-01')
  ) as v(category, key_name, display_name, unit, value_amount, effective_date)
 where not exists (
   select 1 from monitoring_konveksi.pricing_configs c where c.key_name = v.key_name
 );

-- ─── 9. Isi salinan untuk pesanan yang produksinya SUDAH selesai ─────────────
-- Trigger `trg_orders_touch` dimatikan sebentar supaya `updated_at` pesanan tidak ikut berubah
-- (updated_at dipakai pengaman dua-orang-sekaligus dan cadangan tanggal selesai).
alter table monitoring_konveksi.orders disable trigger trg_orders_touch;

update monitoring_konveksi.orders o
   set crew_snapshot = jsonb_build_object(
         'pj',         o.assigned_to,
         'team_id',    o.team_id,
         'member_ids', coalesce(
                         (select to_jsonb(t.member_ids)
                            from monitoring_konveksi.teams t
                           where t.id = o.team_id),
                         '[]'::jsonb),
         'at',         now(),
         'backfill',   true)
 where o.crew_snapshot is null
   and exists (select 1
                 from jsonb_array_elements(
                        case when jsonb_typeof(o.steps) = 'array' then o.steps else '[]'::jsonb end) s
                where s ->> 'key' in ('potong_kain', 'produksi_massal'))
   and not exists (select 1
                     from jsonb_array_elements(
                            case when jsonb_typeof(o.steps) = 'array' then o.steps else '[]'::jsonb end) s
                    where s ->> 'key' in ('potong_kain', 'produksi_massal')
                      and coalesce(s ->> 'isCompleted', 'false') <> 'true');

alter table monitoring_konveksi.orders enable trigger trg_orders_touch;

