-- 007_pricing_salary.sql  (Bagian 5 — Config Harga & Gaji)
--
-- Isi:
--   1. pricing_configs   — riwayat rate gaji per (jenis produksi, tahap) + parameter aturan
--                          (persen PJ, bonus admin). HANYA BISA DITAMBAH, tidak bisa diubah/dihapus
--                          dari aplikasi, supaya gaji bulan lalu tidak pernah ikut berubah.
--   2. salary_payments   — penanda "gaji sudah dibayar" per orang per bulan per kategori.
--   3. salary_audit_log  — jejak tandai/batalkan lunas (tidak bisa diubah dari aplikasi).
--   4. orders.crew_snapshot + trigger — salinan PJ & anggota tim yang dibuat DATABASE saat
--                          tahap produksi selesai, jadi mengubah anggota tim di Pengaturan
--                          tidak mengubah gaji pesanan lama (PRD §11 no. 11a / §17).
--   5. guard_orders_update — salinan versi 006 + penjaga kolom crew_snapshot.
--   6. mark_salary_paid / unmark_salary_paid — satu-satunya jalan menulis salary_payments.
--
-- Prasyarat: 001–006 sudah dijalankan. Aman dijalankan ulang (idempotent).
-- Dijalankan di SQL Editor sebagai postgres (pemilik tabel).
--
-- ⚠ Bagian 9 (isi salinan untuk pesanan yang produksinya SUDAH selesai) memakai susunan
--   PJ/tim pada saat migration dijalankan. Jalankan sebelum mengubah tim/PJ pesanan lama.

begin;

-- ─── 1. Riwayat harga ────────────────────────────────────────────────────────
-- category PRODUKSI : key_name = '{jenis_produksi.value}:{step_key}', mis. 'kaos_polo:produksi_massal'
--                     step_key ∈ potong_kain · produksi_massal · qc · packing (satuan: Rupiah per pcs)
-- category PARAMETER: pj_share_percent · bonus_admin_closing · batas_pcs_bonus_admin · bonus_admin_per_pcs
-- Perubahan harga = INSERT baris baru dengan effective_date baru. Koreksi di hari yang sama =
-- INSERT lagi (id terbesar menang). Gaji dihitung dengan rate yang berlaku pada tanggal tahap selesai.
create table if not exists monitoring_konveksi.pricing_configs (
  id             bigint generated by default as identity primary key,
  category       text not null check (category in ('PRODUKSI', 'PARAMETER')),
  key_name       text not null check (char_length(btrim(key_name)) between 1 and 120),
  display_name   text not null check (char_length(btrim(display_name)) between 1 and 200),
  unit           text not null default 'per_pcs',
  value_amount   numeric(14, 0) not null check (value_amount >= 0),
  effective_date date not null default current_date,
  created_by     uuid default auth.uid() references monitoring_konveksi.users(id) on delete set null,
  created_at     timestamptz not null default timezone('utc', now()),
  constraint pricing_configs_pj_share_range
    check (key_name <> 'pj_share_percent' or value_amount between 0 and 100)
);
create index if not exists pricing_configs_key_idx
  on monitoring_konveksi.pricing_configs (key_name, effective_date desc, id desc);

-- ─── 2. Status pembayaran gaji ───────────────────────────────────────────────
-- Tanpa foreign key ke users (riwayat pembayaran harus tetap ada walau akun dihapus);
-- nama disalin ke user_name.
create table if not exists monitoring_konveksi.salary_payments (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null,
  user_name     text,
  period_month  smallint not null check (period_month between 1 and 12),
  period_year   smallint not null check (period_year between 2020 and 2100),
  kategori      text not null check (kategori in ('produksi', 'qc', 'admin')),
  total_amount  numeric(14, 0) not null check (total_amount >= 0),
  paid_at       timestamptz not null default now(),
  paid_by       uuid references monitoring_konveksi.users(id) on delete set null,
  unique (user_id, period_month, period_year, kategori)
);
create index if not exists salary_payments_period_idx
  on monitoring_konveksi.salary_payments (period_year, period_month);

-- ─── 3. Jejak audit ──────────────────────────────────────────────────────────
create table if not exists monitoring_konveksi.salary_audit_log (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  action        text not null check (action in ('LUNAS', 'BATAL_LUNAS')),
  user_id       uuid not null,
  user_name     text,
  kategori      text not null,
  period_month  smallint not null,
  period_year   smallint not null,
  amount        numeric(14, 0) not null,
  by_id         uuid,
  by_name       text
);
create index if not exists salary_audit_log_idx
  on monitoring_konveksi.salary_audit_log (created_at desc);

-- ─── 4. Salinan PJ & tim di pesanan ──────────────────────────────────────────
alter table monitoring_konveksi.orders
  add column if not exists crew_snapshot jsonb;  -- {pj, team_id, member_ids[], at}

-- Aturan:
--  * Produksi (Potong Kain + Jahit/Produksi) BELUM tuntas  → crew_snapshot = NULL
--  * Produksi tuntas & belum ada salinan                   → salin PJ + anggota tim SEKARANG
--  * Produksi tuntas & PJ/tim diganti SENGAJA lewat Edit Pesanan → salin ulang (koreksi sah;
--    tercatat di Log Aktivitas "Pesanan Diedit")
--  * PJ/tim kosong karena user/tim DIHAPUS (on delete set null) → salinan lama DIPERTAHANKAN
--  * Anggota tim diubah di Pengaturan → TIDAK menyentuh pesanan (salinan sudah beku)
--  * QC gagal membuka lagi Produksi Massal → salinan dibuang; produksi selesai ulang → salin lagi
create or replace function monitoring_konveksi.orders_crew_snapshot()
returns trigger language plpgsql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
declare
  v_total     int;
  v_done      int;
  v_recapture boolean := false;
begin
  select count(*) filter (where s ->> 'key' in ('potong_kain', 'produksi_massal')),
         count(*) filter (where s ->> 'key' in ('potong_kain', 'produksi_massal')
                            and coalesce(s ->> 'isCompleted', 'false') = 'true')
    into v_total, v_done
    from jsonb_array_elements(
           case when jsonb_typeof(new.steps) = 'array' then new.steps else '[]'::jsonb end
         ) as s;

  if v_total = 0 or v_done < v_total then
    new.crew_snapshot := null;
    return new;
  end if;

  if new.crew_snapshot is null then
    v_recapture := true;
  else
    if new.assigned_to is distinct from old.assigned_to
       and not (new.assigned_to is null
                and not exists (select 1 from monitoring_konveksi.users u where u.id = old.assigned_to))
    then
      v_recapture := true;
    end if;
    if new.team_id is distinct from old.team_id
       and not (new.team_id is null
                and not exists (select 1 from monitoring_konveksi.teams t where t.id = old.team_id))
    then
      v_recapture := true;
    end if;
  end if;

  if v_recapture then
    new.crew_snapshot := jsonb_build_object(
      'pj',         new.assigned_to,
      'team_id',    new.team_id,
      'member_ids', coalesce(
                      (select to_jsonb(t.member_ids)
                         from monitoring_konveksi.teams t
                        where t.id = new.team_id),
                      '[]'::jsonb),
      'at',         now()
    );
  end if;
  return new;
end;
$$;

-- Nama diawali "trg_orders_" → berjalan SESUDAH trg_guard_orders_update (urutan abjad), jadi
-- penjaga hanya melihat kiriman dari aplikasi, bukan isian trigger ini.
drop trigger if exists trg_orders_crew_snapshot on monitoring_konveksi.orders;
create trigger trg_orders_crew_snapshot
  before update on monitoring_konveksi.orders
  for each row execute function monitoring_konveksi.orders_crew_snapshot();

-- ─── 5. Penjaga kolom orders (salinan 006 + crew_snapshot) ───────────────────
-- Mengubah fungsi ini lagi? Mulailah dari versi INI (007), bukan 005/006.
create or replace function monitoring_konveksi.guard_orders_update()
returns trigger language plpgsql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
declare
  v_can_flow boolean;
begin
  -- service role / SQL editor / API server: tidak ada pengguna login → lolos
  if auth.uid() is null then return new; end if;

  -- (a) Kolom identitas tidak pernah boleh berubah dari aplikasi.
  --     created_by boleh menjadi NULL (aksi otomatis saat akun penulisnya dihapus).
  if new.id            is distinct from old.id
     or new.created_at    is distinct from old.created_at
     or new.kode_produksi is distinct from old.kode_produksi
     or new.kategori      is distinct from old.kategori
     or (new.created_by is distinct from old.created_by and new.created_by is not null)
  then
    raise exception 'Kode, kategori, dan pembuat pesanan tidak boleh diubah'
      using errcode = '42501';
  end if;

  -- (a2) Salinan susunan pekerja (dasar gaji) hanya diisi trigger database
  if new.crew_snapshot is distinct from old.crew_snapshot then
    raise exception 'Salinan PJ/tim pesanan tidak boleh diubah manual'
      using errcode = '42501';
  end if;

  -- (b) Pindah ke Sampah / pulihkan
  if new.deleted_at is distinct from old.deleted_at then
    if not (   monitoring_konveksi.has_perm('orders', 'delete')
            or monitoring_konveksi.has_perm('trash',  'delete')) then
      raise exception 'Tidak punya izin menghapus/memulihkan pesanan'
        using errcode = '42501';
    end if;
  end if;

  -- (c) Data pemesan, jadwal, catatan, penanggung jawab, tim → hanya yang boleh edit pesanan
  if (   new.nama_pemesan    is distinct from old.nama_pemesan
      or new.no_hp           is distinct from old.no_hp
      or new.alamat_pemesan  is distinct from old.alamat_pemesan
      or new.tanggal_masuk   is distinct from old.tanggal_masuk
      or new.deadline        is distinct from old.deadline
      or new.catatan_pesanan is distinct from old.catatan_pesanan
      or new.assigned_to     is distinct from old.assigned_to
      or (    new.team_id is distinct from old.team_id
          -- kecuali: tim lama sudah tidak ada (dihapus) dan kolom dikosongkan
          and not (    new.team_id is null
                   and not exists (select 1 from monitoring_konveksi.teams t
                                   where t.id = old.team_id))))
     and not monitoring_konveksi.has_perm('orders', 'edit')
  then
    raise exception 'Tidak punya izin mengubah data pesanan'
      using errcode = '42501';
  end if;

  -- (d) Item & jumlah: edit pesanan, atau membuat Approval (produksi.create)
  if (   new.items          is distinct from old.items
      or new.jumlah         is distinct from old.jumlah
      or new.jenis_produksi is distinct from old.jenis_produksi)
     and not (   monitoring_konveksi.has_perm('orders',   'edit')
              or monitoring_konveksi.has_perm('produksi', 'create'))
  then
    raise exception 'Tidak punya izin mengubah item atau jumlah pesanan'
      using errcode = '42501';
  end if;

  -- (e) Tahap, kendala, status: mengerjakan tahap / melapor kendala
  if (   new.steps   is distinct from old.steps
      or new.kendala is distinct from old.kendala
      or new.status  is distinct from old.status)
  then
    v_can_flow :=    monitoring_konveksi.has_perm('orders',    'edit')
                  or monitoring_konveksi.has_perm('produksi',  'create')
                  or monitoring_konveksi.has_perm('produksi',  'edit')
                  or monitoring_konveksi.has_perm('produksi',  'delete')
                  or monitoring_konveksi.has_perm('finishing', 'create')
                  or monitoring_konveksi.has_perm('finishing', 'edit')
                  or monitoring_konveksi.has_perm('finishing', 'delete');
    if not v_can_flow then
      raise exception 'Tidak punya izin mengubah tahap atau status pesanan'
        using errcode = '42501';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_orders_update on monitoring_konveksi.orders;
create trigger trg_guard_orders_update
  before update on monitoring_konveksi.orders
  for each row execute function monitoring_konveksi.guard_orders_update();

-- ─── 6. Tandai / batalkan lunas (satu-satunya jalan menulis salary_payments) ──
-- Izin dicek di dalam fungsi (modul Gaji & Upah → Edit). Nominal dicatat seperti yang dikirim
-- aplikasi (basis perhitungan ada di aplikasi, bukan di database); jejaknya masuk salary_audit_log.
create or replace function monitoring_konveksi.mark_salary_paid(
  p_user_id  uuid,
  p_month    int,
  p_year     int,
  p_kategori text,
  p_amount   numeric
)
returns monitoring_konveksi.salary_payments
language plpgsql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
declare
  v_me      uuid := auth.uid();
  v_amount  numeric := round(p_amount);
  v_name    text;
  v_by_name text;
  v_row     monitoring_konveksi.salary_payments;
begin
  if v_me is null or not monitoring_konveksi.has_perm('salary', 'edit') then
    raise exception 'Tidak punya izin menandai gaji (butuh izin Gaji & Upah → Edit)'
      using errcode = '42501';
  end if;
  if p_kategori is null or p_kategori not in ('produksi', 'qc', 'admin') then
    raise exception 'Kategori gaji tidak dikenal' using errcode = '22023';
  end if;
  if p_month is null or p_month not between 1 and 12
     or p_year is null or p_year not between 2020 and 2100 then
    raise exception 'Periode gaji tidak valid' using errcode = '22023';
  end if;
  if v_amount is null or v_amount < 0 then
    raise exception 'Nominal gaji tidak valid' using errcode = '22023';
  end if;

  select name into v_name from monitoring_konveksi.users where id = p_user_id;
  if not found then
    raise exception 'Penerima gaji tidak ditemukan' using errcode = '22023';
  end if;
  select name into v_by_name from monitoring_konveksi.users where id = v_me;

  -- bentrok (sudah ditandai lunas oleh orang lain) → galat 23505, aplikasi memuat ulang
  insert into monitoring_konveksi.salary_payments
    (user_id, user_name, period_month, period_year, kategori, total_amount, paid_by)
  values
    (p_user_id, v_name, p_month, p_year, p_kategori, v_amount, v_me)
  returning * into v_row;

  insert into monitoring_konveksi.salary_audit_log
    (action, user_id, user_name, kategori, period_month, period_year, amount, by_id, by_name)
  values
    ('LUNAS', p_user_id, v_name, p_kategori, p_month, p_year, v_amount, v_me, v_by_name);

  return v_row;
end;
$$;

create or replace function monitoring_konveksi.unmark_salary_paid(
  p_user_id  uuid,
  p_month    int,
  p_year     int,
  p_kategori text
)
returns boolean
language plpgsql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
declare
  v_me      uuid := auth.uid();
  v_by_name text;
  v_row     monitoring_konveksi.salary_payments;
begin
  if v_me is null or not monitoring_konveksi.has_perm('salary', 'edit') then
    raise exception 'Tidak punya izin membatalkan status lunas (butuh izin Gaji & Upah → Edit)'
      using errcode = '42501';
  end if;

  delete from monitoring_konveksi.salary_payments
   where user_id = p_user_id and period_month = p_month
     and period_year = p_year and kategori = p_kategori
  returning * into v_row;

  if not found then
    return false;   -- sudah dibatalkan orang lain
  end if;

  select name into v_by_name from monitoring_konveksi.users where id = v_me;
  insert into monitoring_konveksi.salary_audit_log
    (action, user_id, user_name, kategori, period_month, period_year, amount, by_id, by_name)
  values
    ('BATAL_LUNAS', v_row.user_id, v_row.user_name, v_row.kategori,
     v_row.period_month, v_row.period_year, v_row.total_amount, v_me, v_by_name);
  return true;
end;
$$;

