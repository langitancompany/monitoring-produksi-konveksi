-- 001_base_umum.sql
--
-- Fondasi schema Konveksi: tabel umum (users, notifikasi, token push,
-- pengumuman, akses direksi), fungsi pengecek hak akses, dan aturan RLS.
-- Disusun dari SKEMA ASLI schema `monitoring_sablon` (hasil query kolom,
-- policy, fungsi, dan trigger tanggal 17 Okt 2026) — polanya sama, supaya
-- perilaku hak akses di Konveksi identik dengan Sablon.
--
-- Jalankan di SQL Editor Supabase (sebagai postgres). Aman dijalankan ulang.
-- Setelah ini jalankan 002_konveksi_core.sql.
--
-- Perbedaan yang SENGAJA dari Sablon:
--  * guard_users_update juga menjaga kolom `roles` (di Sablon kolom ini lolos,
--    padahal dipakai fin_perm & policy orders → lihat docs/PRD.md §10).
--  * notifications.created_at memakai timestamptz (di Sablon: tanpa zona waktu).
--  * get_public_tables hanya bisa dipanggil lewat service role (server).
--  * users.username (= email login) unik; user_fcm_tokens.user_id unik (kode
--    memakai upsert onConflict: 'user_id').
--  * Tabel users TIDAK punya kolom password. Akun login dibuat/diubah lewat
--    API server (/api/users) langsung di Supabase Auth.

create schema if not exists monitoring_konveksi;

-- ─── Tabel ───────────────────────────────────────────────────────────────────

create table if not exists monitoring_konveksi.users (
  id           uuid primary key default gen_random_uuid(),   -- harus SAMA dengan auth.users.id agar bisa login
  username     text not null unique,
  name         text not null,
  role         text,                                          -- role utama (lib/roles.ts → primaryRole)
  roles        text[],                                        -- semua role (boleh lebih dari satu)
  permissions  jsonb default '{}'::jsonb,
  address      text,
  dob          date,
  avatar_url   text,
  no_wa        text,
  created_at   timestamptz not null default timezone('utc', now())
);

create table if not exists monitoring_konveksi.notifications (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null,
  title       text not null,
  message     text not null,
  is_read     boolean default false,
  created_at  timestamptz default now(),
  order_id    uuid
);
create index if not exists notifications_user_idx
  on monitoring_konveksi.notifications (user_id, created_at desc);

create table if not exists monitoring_konveksi.user_fcm_tokens (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null unique,
  token       text not null,
  created_at  timestamptz not null default timezone('utc', now()),
  updated_at  timestamptz not null default timezone('utc', now())
);

create table if not exists monitoring_konveksi.announcements (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  message     text not null,
  type        text default 'info',
  is_active   boolean default true,
  created_by  text,
  created_at  timestamptz default now(),
  expires_at  timestamptz
);

create table if not exists monitoring_konveksi.direksi_access (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null,
  unit_code   text not null,
  role        text not null default 'direksi',
  created_at  timestamptz default now(),
  unique (user_id, unit_code)
);

-- ─── Fungsi pengecek hak akses (SECURITY DEFINER, sama dengan Sablon) ────────

-- Role yang dianggap staf. Tambahkan di sini bila ada role baru (mis. 'penjahit').
create or replace function monitoring_konveksi.is_staff()
returns boolean language sql stable security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select exists (
    select 1 from monitoring_konveksi.users
    where id = auth.uid()
      and role in ('admin', 'supervisor', 'manager', 'produksi', 'qc')
  );
$$;

create or replace function monitoring_konveksi.is_supervisor()
returns boolean language sql stable security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select exists (
    select 1 from monitoring_konveksi.users
    where id = auth.uid() and role = 'supervisor'
  );
$$;

create or replace function monitoring_konveksi.is_admin_or_supervisor()
returns boolean language sql stable security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select exists (
    select 1 from monitoring_konveksi.users
    where id = auth.uid() and role in ('admin', 'supervisor')
  );
$$;

-- has_perm('orders','create') → true bila supervisor atau permissions.orders.create = true
create or replace function monitoring_konveksi.has_perm(p_module text, p_action text)
returns boolean language sql stable security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select coalesce((
    select u.role = 'supervisor'
        or (u.permissions -> p_module ->> p_action) = 'true'
    from monitoring_konveksi.users u
    where u.id = auth.uid()
  ), false);
$$;

create or replace function monitoring_konveksi.get_user_units(p_user_id uuid)
returns table (unit_code text) language sql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select unit_code from monitoring_konveksi.direksi_access where user_id = p_user_id;
$$;

-- Dipakai /api/backup (server, service role)
create or replace function monitoring_konveksi.get_public_tables()
returns table (table_name text) language sql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
  select tablename::text
  from pg_tables
  where schemaname = 'monitoring_konveksi'
  order by tablename;
$$;
revoke all on function monitoring_konveksi.get_public_tables() from public, anon, authenticated;
grant execute on function monitoring_konveksi.get_public_tables() to service_role;

-- ─── Penjaga tabel users ─────────────────────────────────────────────────────
-- User biasa hanya boleh mengubah profilnya (nama, alamat, tgl lahir, foto, no WA).
-- Tidak boleh mengubah id, username, role, ROLES, atau permissions.
create or replace function monitoring_konveksi.guard_users_update()
returns trigger language plpgsql security definer
set search_path to 'monitoring_konveksi', 'pg_temp'
as $$
begin
  -- service role / SQL editor (tanpa auth.uid) dibiarkan
  if auth.uid() is null then return new; end if;

  -- admin & supervisor boleh mengelola user
  if monitoring_konveksi.is_admin_or_supervisor() then return new; end if;

  if new.id          is distinct from old.id
  or new.role        is distinct from old.role
  or new.roles       is distinct from old.roles
  or new.permissions is distinct from old.permissions
  or new.username    is distinct from old.username then
    raise exception 'Tidak diizinkan mengubah role, permission, atau kredensial'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_users_update on monitoring_konveksi.users;
create trigger trg_guard_users_update
  before update on monitoring_konveksi.users
  for each row execute function monitoring_konveksi.guard_users_update();

-- ─── Akses dasar ─────────────────────────────────────────────────────────────
-- (Konveksi tidak punya halaman publik, jadi role `anon` tidak diberi akses apa pun.)
grant usage on schema monitoring_konveksi to authenticated, service_role;
grant select, insert, update, delete on all tables in schema monitoring_konveksi to authenticated, service_role;
grant usage, select on all sequences in schema monitoring_konveksi to authenticated, service_role;
grant execute on all functions in schema monitoring_konveksi to authenticated, service_role;
revoke execute on function monitoring_konveksi.get_public_tables() from authenticated;

alter default privileges in schema monitoring_konveksi
  grant select, insert, update, delete on tables to authenticated, service_role;
alter default privileges in schema monitoring_konveksi
  grant usage, select on sequences to authenticated, service_role;

-- ─── RLS ─────────────────────────────────────────────────────────────────────
alter table monitoring_konveksi.users           enable row level security;
alter table monitoring_konveksi.notifications   enable row level security;
alter table monitoring_konveksi.user_fcm_tokens enable row level security;
alter table monitoring_konveksi.announcements   enable row level security;
alter table monitoring_konveksi.direksi_access  enable row level security;

-- users
drop policy if exists "Lihat profil sendiri atau semua jika admin/supervisor" on monitoring_konveksi.users;
create policy "Lihat profil sendiri atau semua jika admin/supervisor" on monitoring_konveksi.users
  for select to authenticated
  using (auth.uid() = id or monitoring_konveksi.is_admin_or_supervisor());

drop policy if exists "Update profil sendiri atau semua jika admin/supervisor" on monitoring_konveksi.users;
create policy "Update profil sendiri atau semua jika admin/supervisor" on monitoring_konveksi.users
  for update to authenticated
  using (auth.uid() = id or monitoring_konveksi.is_admin_or_supervisor());

drop policy if exists "Hanya admin/supervisor boleh buat user baru" on monitoring_konveksi.users;
create policy "Hanya admin/supervisor boleh buat user baru" on monitoring_konveksi.users
  for insert to authenticated
  with check (monitoring_konveksi.is_admin_or_supervisor());

drop policy if exists "Hanya admin/supervisor boleh hapus user" on monitoring_konveksi.users;
create policy "Hanya admin/supervisor boleh hapus user" on monitoring_konveksi.users
  for delete to authenticated
  using (monitoring_konveksi.is_admin_or_supervisor());

-- notifications
drop policy if exists "User bisa lihat notifikasi sendiri" on monitoring_konveksi.notifications;
create policy "User bisa lihat notifikasi sendiri" on monitoring_konveksi.notifications
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "User bisa update notifikasi sendiri" on monitoring_konveksi.notifications;
create policy "User bisa update notifikasi sendiri" on monitoring_konveksi.notifications
  for update to authenticated using (auth.uid() = user_id);

drop policy if exists "Staff bisa membuat notifikasi untuk user lain" on monitoring_konveksi.notifications;
create policy "Staff bisa membuat notifikasi untuk user lain" on monitoring_konveksi.notifications
  for insert to authenticated with check (monitoring_konveksi.is_staff());

-- user_fcm_tokens
drop policy if exists "User kelola token FCM miliknya sendiri" on monitoring_konveksi.user_fcm_tokens;
create policy "User kelola token FCM miliknya sendiri" on monitoring_konveksi.user_fcm_tokens
  for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- announcements
drop policy if exists "Semua staff bisa baca pengumuman" on monitoring_konveksi.announcements;
create policy "Semua staff bisa baca pengumuman" on monitoring_konveksi.announcements
  for select to authenticated using (true);

drop policy if exists "Admin/supervisor bisa kelola pengumuman" on monitoring_konveksi.announcements;
create policy "Admin/supervisor bisa kelola pengumuman" on monitoring_konveksi.announcements
  for all to authenticated
  using (monitoring_konveksi.is_admin_or_supervisor())
  with check (monitoring_konveksi.is_admin_or_supervisor());

-- direksi_access
drop policy if exists "User bisa lihat akses direksi miliknya sendiri" on monitoring_konveksi.direksi_access;
create policy "User bisa lihat akses direksi miliknya sendiri" on monitoring_konveksi.direksi_access
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Admin/supervisor bisa kelola direksi_access" on monitoring_konveksi.direksi_access;
create policy "Admin/supervisor bisa kelola direksi_access" on monitoring_konveksi.direksi_access
  for all to authenticated
  using (monitoring_konveksi.is_admin_or_supervisor())
  with check (monitoring_konveksi.is_admin_or_supervisor());

-- ─── Realtime (lonceng notifikasi & banner pengumuman) ───────────────────────
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    begin alter publication supabase_realtime add table monitoring_konveksi.notifications;
    exception when duplicate_object then null; end;
    begin alter publication supabase_realtime add table monitoring_konveksi.announcements;
    exception when duplicate_object then null; end;
  end if;
end $$;
